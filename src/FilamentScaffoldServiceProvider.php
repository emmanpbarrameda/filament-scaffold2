<?php

namespace Emmanpbarrameda\FilamentScaffold2;

use Emmanpbarrameda\FilamentScaffold2\Models\Scaffold;
use Emmanpbarrameda\FilamentScaffold2\Testing\TestsFilamentScaffold;
use Illuminate\Support\Facades\Gate;
use Livewire\Features\SupportTesting\Testable;
use Spatie\LaravelPackageTools\Package;
use Spatie\LaravelPackageTools\PackageServiceProvider;

/********************************************
 * ? Package service provider (auto-discovered via composer.json extra.laravel)
 * Publishes config/filament-scaffold2.php (tag: filament-scaffold2-config)
 * Registers the app's ScaffoldPolicy for the package's Scaffold model (see registerPolicy())
 ********************************************/
class FilamentScaffoldServiceProvider extends PackageServiceProvider
{
    public static string $name = 'filament-scaffold2';

    public function configurePackage(Package $package): void
    {
        $package
            ->name(static::$name)
            ->hasConfigFile();
    }

    public function packageBooted(): void
    {
        Testable::mixin(new TestsFilamentScaffold);

        $this->registerPolicy();
    }

    /* =========================================
     * ! MARK: Policy for the Scaffold model
     * ? detector: the model lives in this package, so Laravel's policy auto-discovery never looks in
     *   App\Policies. Without a policy, Filament allows everyone and the Shield checkboxes do nothing.
     * ? detector: the policy itself is generated by the app (shield:generate --resource=ScaffoldResource),
     *   so its permission names follow the app's own Shield config.
     * ========================================= */
    protected function registerPolicy(): void
    {
        $policy = config('filament-scaffold2.policy', 'App\\Policies\\ScaffoldPolicy');

        // STEP 1: Nothing to register (no policy class configured or generated yet)
        if (! is_string($policy) || $policy === '' || ! class_exists($policy)) {
            return;
        }

        // STEP 2: Keep a policy the app already registered itself (Gate::policy in AppServiceProvider)
        if (array_key_exists(Scaffold::class, Gate::policies())) {
            return;
        }

        Gate::policy(Scaffold::class, $policy);
    }
}
